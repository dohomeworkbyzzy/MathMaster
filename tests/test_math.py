"""Check actual mathematical relationships, not only the engine's verified flag."""
import pytest
import sympy as s
from backend.engine import compute
from backend.parser import parse, MathInputError
from backend.matrix import read_matrix,mequal
from backend.jobs import run_job,JobError

x=s.Symbol('x',real=True)

def flatten(steps):
    for st in steps:
        yield st
        yield from flatten(st['children'])

def check_steps(out):
    for st in flatten(out['steps']):
        assert {'step_id','rule','before_latex','after_latex','explanation_zh','children'}<=st.keys()
        assert st['verified'],st
        v=st['verification'];kind=v['kind']
        # These strings are solely generated by our own engine in this test process.
        # They never come from user input; production uses only the closed parser.
        locals_={k:s.Symbol(k,real=True) for k in ('x','y','z','a','b','t')}
        def expr(text):return s.sympify(text,locals=locals_)
        if kind=='antiderivative':
            var=expr(v['variable']);assert s.simplify(s.diff(expr(v['after']),var)-expr(v['integrand']))==0
        elif kind=='real_log_conversion':
            assert s.simplify(s.diff(expr(v['analytic']),expr(v['variable']))-expr(v['integrand']))==0
            p=s.Symbol('p',positive=True)
            assert s.diff(s.log(s.Abs(p)),p)==1/p
            assert -s.diff(s.log(s.Abs(-p)),p)==-1/p
            assert all(not expr(c).has(expr(v['variable'])) for c in v['coefficients'])
        elif kind=='rank':
            assert expr(v['before']).rank()==expr(v['after'])
        elif kind=='substitution':
            assert s.simplify(expr(v['integrand'])-expr(v['reconstructed']))==0
        elif kind=='derivative':
            assert s.simplify(s.diff(expr(v['expression']),expr(v['variable']))-expr(v['after']))==0
        elif kind=='definite_limits':
            assert s.simplify(expr(v['after'])-(expr(v['right_limit'])-expr(v['left_limit'])))==0
            assert s.simplify(expr(v['after'])-expr(v['sympy_result']))==0
        elif kind=='elementary_row':
            before=read_matrix(st['before_matrix']);after=read_matrix(st['after_matrix']);ref=before.copy();i=st['target_row']-1
            if st['operation_type']=='swap':ref.row_swap(i,st['source_row']-1)
            elif st['operation_type']=='scale':ref.row_op(i,lambda a,j:a*parse(st['coefficient']))
            else:ref.row_op(i,lambda a,j:a+parse(st['coefficient'])*before[st['source_row']-1,j])
            assert mequal(ref,after)
            if before.rows==before.cols:assert s.simplify(after.det()-parse(st['determinant_multiplier'])*before.det())==0
        elif kind in ('equality','determinant','matrix_identity'):
            left,right=expr(v['before']),expr(v['after'])
            if isinstance(left,s.Determinant):left=left.doit()
            if isinstance(left,s.MatrixBase):assert mequal(left,right)
            else:assert s.simplify(left-right)==0

@pytest.mark.parametrize('expression,result,rule',[
 ('x*exp(x)',(x-1)*s.exp(x),'PartsRule'),
 ('2x/(x^2+1)',s.log(x*x+1),'URule'),
 ('1/(1+x^2)',s.atan(x),'ArctanRule'),
 ('sin(x)^2',x/2-s.sin(2*x)/4,'RewriteRule'),
 ('log(x)',x*s.log(x)-x,'PartsRule'),
 ('(x+1)/(x*(x+2))',s.log(x)/2+s.log(x+2)/2,'RewriteRule')])
def test_integrals(expression,result,rule):
    out=compute('integrate',{'expression':expression})
    assert out['verified'] and out['steps_complete']
    got=s.sympify(out['exact_result'][:-4],locals={'x':x})
    derivative=s.simplify(s.diff(got-result,x))
    if derivative!=0:
        assert all(s.simplify(derivative.subs(x,v))==0 for v in (s.Rational(1,2),1,3))
    assert out['result_latex'].endswith(' + C')
    assert rule in [st['rule'] for st in flatten(out['steps'])]
    check_steps(out)

@pytest.mark.parametrize('expression,lower,upper,expected',[
 ('x^2','0','1',s.Rational(1,3)),('x^2','1','0',-s.Rational(1,3)),
 ('exp(-x)','0','oo',s.S.One),('1/x^2','1','oo',s.S.One),
 ('1/sqrt(x)','0','1',s.Integer(2))])
def test_definite_limits(expression,lower,upper,expected):
    out=compute('integrate',dict(expression=expression,lower=lower,upper=upper))
    assert out['verified'];assert s.sympify(out['exact_result'])==expected
    check_steps(out)

