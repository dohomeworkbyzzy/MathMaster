def test_reciprocal_real_both_signs():
    out=compute('integrate',{'expression':'1/x'})
    assert out['exact_result']=='log(Abs(x)) + C' and out['verified']
    got=parse(out['exact_result'][:-4]);residual=s.diff(got,x)-1/x
    assert all(s.simplify(residual.subs(x,v))==0 for v in (-3,-1,1,4))
    check_steps(out)

