import {test,expect} from '@playwright/test';

test('AI shows the shared saved draft beside dialogue and preserves notes',async({page,request})=>{
 const prefix='AI原题库-'+Date.now();
 const q=(await (await request.post('/api/questions',{data:{number:prefix,text:'求 sin(x) 的导数',subject:'数学二',confirmed:true}})).json()).id;
 const result=await (await request.post('/api/math/differentiate',{data:{expression:'sin(x)',question_id:q}})).json();
 let session:any;
 await page.route('**/api/ai/provider',route=>route.fulfill({json:{configured:true,base_url:'https://api.deepseek.com',model_id:'deepseek-flash'}}));
 await page.route('**/api/ai/sessions/*/turns',async route=>{
  const body=route.request().postDataJSON();
  expect(body.text).toBe('先用基本求导公式，帮我算这一步');
  session={...session,version:1,busy:false,turns:[{id:'test-turn',request_id:body.request_id,user_text:body.text,message:'求导结果已列出。',status:'complete',error:''}],state:{...session.state,cards:[{number:1,tool:'math.differentiate',label:'求导',valid:true,input:{expression:'sin(x)'},result,saved_result:result}],next_question:'这个结果对应哪条求导规则？',current_latex:'\\cos(x)'}};
  await route.fulfill({status:202,json:session});
 });
 page.on('response',async response=>{if(response.url().endsWith('/api/questions/'+q+'/ai')&&response.ok())session=await response.json();});
 await page.goto('/');await page.getByRole('button',{name:'本地题库',exact:true}).click();
 await page.getByLabel('搜索题库').fill(prefix);
 await page.getByRole('button',{name:'开始练习',exact:true}).click();
 await page.getByLabel('解题笔记',{exact:true}).fill('原有笔记保留');
 await page.getByRole('button',{name:'AI 解题',exact:true}).click();
 await expect(page.getByRole('region',{name:'AI 解题'})).toBeVisible();
 await expect.poll(()=>session?.question_id).toBe(q);
 await expect(page.locator('.ai-model')).toContainText('DeepSeek V4.1 Flash');
 await page.getByRole('button',{name:'本地缓存',exact:true}).click();
 await expect(page.locator('.ai-cache-panel')).toContainText('本地缓存已开启');
 await page.getByRole('button',{name:'清空缓存',exact:true}).click();
 await expect.poll(async()=>(await (await request.get('/api/ai/cache')).json()).entries).toBe(0);
 await page.getByRole('button',{name:'本地缓存',exact:true}).click();
 await expect(page.getByLabel('电子草稿画布')).toBeVisible();
 await expect(page.getByRole('region',{name:'草稿区'})).toBeVisible();
 const paper=(await page.getByLabel('电子草稿画布').boundingBox())!;
 await page.mouse.move(paper.x+30,paper.y+30);await page.mouse.down();await page.mouse.move(paper.x+100,paper.y+60);await page.mouse.up();
 await expect.poll(async()=>JSON.parse((await (await request.get('/api/questions/'+q)).json()).attempt?.draft||'[]').length).toBe(1);
 await page.getByLabel('描述解题思路').fill('先用基本求导公式，帮我算这一步');
 await page.getByRole('button',{name:'发送',exact:true}).click();
 await expect(page.locator('.ai-next')).toContainText('哪条求导规则');
 await expect(page.locator('.ai-cards')).toContainText('cos');
 await page.screenshot({path:'test-results/ai-shared-draft.png'});
 await page.getByRole('button',{name:'写入本题笔记'}).click();
 await expect.poll(async()=>{const saved=await (await request.get('/api/questions/'+q)).json();return saved.calculations[0]?.id;}).toBe(result.history_id);
 await page.setViewportSize({width:800,height:600});
 await expect(page.getByLabel('描述解题思路')).toBeVisible();
 const box=(await page.getByRole('region',{name:'AI 解题'}).boundingBox())!;
 expect(box.x).toBeGreaterThanOrEqual(0);expect(box.x+box.width).toBeLessThanOrEqual(801);
 const problem=(await page.getByRole('region',{name:'题目区'}).boundingBox())!;
 expect(problem.x+problem.width).toBeLessThanOrEqual(box.x+2);
 await page.setViewportSize({width:600,height:680});
 const narrowQuestion=(await page.getByRole('region',{name:'题目区'}).boundingBox())!;
 const narrowAI=(await page.getByRole('region',{name:'AI 解题'}).boundingBox())!;
 expect(narrowQuestion.y+narrowQuestion.height).toBeLessThanOrEqual(narrowAI.y+2);
 await expect(page.getByLabel('描述解题思路')).toBeVisible();
 await page.getByRole('button',{name:'收起 AI 解题'}).click();
 await expect(page.getByRole('region',{name:'AI 解题'})).toHaveCount(0);
 await expect(page.getByLabel('电子草稿画布')).toBeVisible();
 await page.getByRole('button',{name:'笔记与答案',exact:true}).click();
 await expect(page.getByLabel('解题笔记',{exact:true})).toHaveValue('原有笔记保留');
 expect(JSON.parse((await (await request.get('/api/questions/'+q)).json()).attempt.draft)).toHaveLength(1);
 await expect(page.locator('.note-calculations')).toContainText('cos');
});
